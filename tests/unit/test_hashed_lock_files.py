def test_dependabot_compiles_the_locks_with_uv() -> None:
    """The `pip` updater would recompile with pip-compile, for one platform only."""
    updates = yaml.safe_load(_text(".github/dependabot.yml"))["updates"]
    ecosystems = sorted(update["package-ecosystem"] for update in updates)
