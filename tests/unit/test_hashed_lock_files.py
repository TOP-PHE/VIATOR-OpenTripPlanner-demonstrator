# ── the CI step that compiles every lock again ────────────────────────────────────────────


def test_the_lock_check_runs_right_after_the_install_and_compiles_as_documented() -> None:
    script = _lock_check_script()
    names = [lock.removesuffix(".txt") for lock in LOCKS.values()]
    assert f"for name in {' '.join(names)}; do" in script
    assert '--emit-build-options "$name.in" -c "$pins" -o "$fresh"' in script
    one_line = re.sub(r"\s*\\\n\s*", " ", script)
    # `python -m uv`: the uv of the lock, installed in this Python, never another on PATH.
    compile_quiet = "python -m " + COMPILE.replace("compile", "compile --quiet")
    assert one_line.count(compile_quiet + ' "$name.in"') == 1
    assert re.findall(r"(?<!-m )\buv pip\b", one_line) == []

    # After the install, which brings the uv it runs, and before every other tool.
    names_in_order = [step.get("name") for step in _python_steps()]
    assert names_in_order.index(LOCK_CHECK) == names_in_order.index("Install dependencies") + 1
    assert _direct_pins("requirements-dev.in")["uv"][0] == "=="

    # The spec gives the same commands to whoever adds or upgrades a package.
    spec = _text("VIATOR-technical-spec.md")
    for source, lock in LOCKS.items():
        assert f"{COMPILE} {source} -o {lock}" in spec, source


# The stand-in for `python -m uv` (a `python` first on PATH): it writes the committed lock again, as uv does when the source asks
# for nothing the lock's versions (its constraints) do not give, unless told to write
# something else, or to fail as uv fails when the source and the versions disagree.
_FAKE_UV = """#!/usr/bin/env bash
set -euo pipefail
# Only `python -m uv ...`: the step must run the uv of the lock.
if [ "${1:-}" != "-m" ] || [ "${2:-}" != "uv" ]; then echo "zz: not python -m uv" >&2; exit 4; fi
shift 2
printf '%s\\n' "$*" >> "$ZZ_CALLS"
out=""
previous=""
for argument in "$@"; do
  if [ "$previous" = "-o" ]; then out="$argument"; fi
  previous="$argument"
done
lock="${out##*/}"
# A lock already at the output would lend uv its hashes: the step must give a new file.
if [ -e "$out" ]; then echo "zz: the output file exists" >&2; exit 3; fi
case "$ZZ_CHANGE:$lock" in
  fails:*|unsatisfiable:requirements-dev.txt) echo "zz: no solution" >&2; exit 1 ;;
esac
cp "$lock" "$out"
case "$ZZ_CHANGE:$lock" in
  notes:*) sed -i -e 's/^#    uv pip compile .*/#    uv pip compile zz/' -e 's/# via .*/# via zz/' "$out" ;;
  pin:requirements.txt) sed -i 's/^zz-one==2\\.0 /zz-one==2.1 /' "$out" ;;
  hash:requirements-build.txt) sed -i 's/sha256:9/sha256:8/' "$out" ;;
  added:requirements-dev.txt) printf 'zz-new==1.0 \\\\\\n    --hash=sha256:%s\\n' "$(printf '7%.0s' $(seq 64))" >> "$out" ;;
esac
"""


def _run_lock_check(
    tmp_path: Path, locks: dict[str, str | None], change: str
) -> tuple[subprocess.CompletedProcess[str], list[str], Path]:
    """Run the CI step's script in a folder holding `locks` (None: no such file), with
    the stand-in for `python -m uv` first on PATH, as GitHub runs a `run:` (bash -eo pipefail)."""
    folder = tmp_path / "repository"
    folder.mkdir()
    for lock, content in locks.items():
        if content is not None:
            (folder / lock).write_text(content, encoding="utf-8", newline="\n")
    tools = tmp_path / "tools"
    tools.mkdir()
    uv = tools / "python"
    uv.write_text(_FAKE_UV, encoding="utf-8", newline="\n")
    uv.chmod(0o755)
    script = tmp_path / "step.sh"
    script.write_text(_lock_check_script(), encoding="utf-8", newline="\n")
    runner = tmp_path / "runner"
    runner.mkdir()
    calls = tmp_path / "calls.txt"
    calls.touch()
    bash = shutil.which("bash")
    assert bash is not None
    result = subprocess.run(
        [bash, "--noprofile", "--norc", "-eo", "pipefail", str(script)],
        cwd=folder,
        env={
            "PATH": str(tools) + os.pathsep + os.environ.get("PATH", ""),
            "RUNNER_TEMP": str(runner),
            "ZZ_CALLS": str(calls),
            "ZZ_CHANGE": change,
        },
        capture_output=True,
        text=True,
        check=False,
        timeout=60,
    )
    return result, calls.read_text(encoding="utf-8").splitlines(), runner


def _invented_lock(name: str) -> str:
    return (
        f"{LOCK_HEADER}\n#    uv pip compile\n{ONLY_WHEELS}\n\n{name}==2.0 \\\n"
        f"    --hash=sha256:{'9' * 64}\n    # via -r zz.in\n"
    )


def _errors(result: subprocess.CompletedProcess[str]) -> list[str]:
    return [line for line in result.stdout.splitlines() if line.startswith("::error::")]


@pytest.mark.parametrize(
    ("change", "stale"),
    [
        pytest.param("none", None, id="the-same"),
        pytest.param("notes", None, id="only-the-notes-of-uv-differ"),
        pytest.param("pin", "requirements.txt", id="a-pin-not-locked"),
        pytest.param("hash", "requirements-build.txt", id="a-hash-changed"),
        pytest.param("added", "requirements-dev.txt", id="a-package-not-locked"),
        pytest.param("unsatisfiable", "requirements-dev.in", id="a-pin-the-lock-lacks"),
    ],
)
def test_the_lock_check_fails_on_a_lock_its_source_does_not_compile_to(
    tmp_path: Path, change: str, stale: str | None
) -> None:
    names = {"requirements.txt": "zz-one", "requirements-dev.txt": "zz-two"}
    locks: dict[str, str | None] = {
        lock: _invented_lock(names.get(lock, "zz-three")) for lock in LOCKS.values()
    }
    result, calls, runner = _run_lock_check(tmp_path, locks, change)

    errors = _errors(result)
    assert [error.split()[0].removeprefix("::error::") for error in errors] == (
        [stale] if stale else []
    )
    assert result.returncode == (1 if stale else 0)
    if stale is None:
        assert "Each lock file is what its source compiles to." in result.stdout
    else:
        source = stale.replace(".txt", ".in")
        assert f"edit {source}, run the compile command of VIATOR-technical-spec.md 15.2.5" in (
            result.stdout
        )
    # Every lock compiled with the command of 15.2.5, its versions as constraints, into a
    # file of its own.
    assert calls == [
        f"pip compile --quiet --universal --python-version 3.14 --generate-hashes "
        f"--emit-build-options {source} -c {runner / lock.replace('.txt', '.pins.txt')} "
        f"-o {runner / lock}"
        for source, lock in LOCKS.items()
    ]
    # The constraints are the lock's packages with their versions, nothing else.
    for lock in LOCKS.values():
        pins = (runner / lock.replace(".txt", ".pins.txt")).read_text(encoding="utf-8")
        assert pins == f"{names.get(lock, 'zz-three')}==2.0\n"


@pytest.mark.parametrize("broken", ["missing", "empty", "no-package"])
def test_the_lock_check_names_a_lock_missing_or_empty_and_checks_the_others(
    tmp_path: Path, broken: str
) -> None:
    locks: dict[str, str | None] = {
        lock: _invented_lock(f"zz-p{number}") for number, lock in enumerate(LOCKS.values())
    }
    locks["requirements.txt"] = {"missing": None, "empty": "", "no-package": ONLY_WHEELS + "\n"}[
        broken
    ]
    result, calls, _ = _run_lock_check(tmp_path, locks, "none")

    assert result.returncode == 1
    assert _errors(result) == [
        "::error::requirements.txt is missing or holds no package. Compile it from "
        "requirements.in with the command of VIATOR-technical-spec.md 15.2.5 and commit "
        "both files."
    ]
    # The other locks were compiled and compared all the same.
    assert [call.split()[-1].split("/")[-1] for call in calls] == [
        "requirements-dev.txt",
        "requirements-build.txt",
    ]


def test_the_lock_check_names_every_source_uv_cannot_compile(tmp_path: Path) -> None:
    locks: dict[str, str | None] = {lock: _invented_lock("zz-one") for lock in LOCKS.values()}
    result, calls, _ = _run_lock_check(tmp_path, locks, "fails")

    assert result.returncode == 1
    assert [line.split()[0] for line in _errors(result)] == [f"::error::{s}" for s in LOCKS]
    assert "cannot be compiled to the versions of" in result.stdout
    assert "zz: no solution" in result.stderr
    assert len(calls) == len(LOCKS)


