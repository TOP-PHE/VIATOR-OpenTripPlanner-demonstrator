"""The Python packages come from hashed lock files (VIATOR-technical-spec.md 15.2.5).

Each `requirements*.in` source holds the pins chosen by hand; `uv pip compile`
turns it into a lock file (`requirements*.txt`) holding every package, indirect
ones included, with its exact version and the sha256 of its files, for every
platform at once (Linux CI, the linux/amd64 web image, a Windows workstation).
Every `pip install` of the workflows and of the web Dockerfile reads a lock with
`--require-hashes --only-binary :all:` (SonarQube githubactions:S8544 / S8541:
nothing resolved at install time, no package's build script run). CI's Python
job compiles each source again and fails when the lock differs ("Lock files
match their sources"); the tests below run that step's script itself with a
stand-in for uv.
"""

from __future__ import annotations

import os
import re
import shutil
import subprocess
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parents[2]

# Source to lock file, in the order the CI step compiles them.
LOCKS = {
    "requirements.in": "requirements.txt",
    "requirements-dev.in": "requirements-dev.txt",
    "requirements-build.in": "requirements-build.txt",
}
# The one line of a source that includes another source.
INCLUDES = {"requirements-dev.in": "-r requirements.in"}
ONLY_WHEELS = "--only-binary :all:"
COMPILE = "uv pip compile --universal --python-version 3.14 --generate-hashes --emit-build-options"
LOCK_HEADER = "# This file was autogenerated by uv via the following command:"
LOCK_CHECK = "Lock files match their sources"
INSTALL = "--require-hashes --only-binary :all: -r"

# A source line: a name, extras, `==` or `>=` and a version, then an optional comment.
_PIN = re.compile(r"^(?P<name>[A-Za-z0-9._-]+)(?:\[[a-z,]+\])?(?P<op>==|>=)(?P<version>[^\s#;]+)")
# A package of a lock: its normalised name, `==`, the version, an optional marker, and
# the `\` that carries its hashes onto the next lines.
_LOCK_ENTRY = re.compile(r"^(?P<name>[a-z0-9-]+)==(?P<version>[^\s;]+)(?: ; (?P<marker>.+))? \\$")
_LOCK_HASH = re.compile(r"^    --hash=sha256:[0-9a-f]{64}(?: \\)?$")


def _text(relative: str) -> str:
    return (ROOT / relative).read_text(encoding="utf-8")


def _normalised(name: str) -> str:
    """The name of a package as a lock file writes it (PEP 503)."""
    return re.sub(r"[-_.]+", "-", name).lower()


def _source_lines(source: str) -> list[str]:
    lines = []
    for raw in _text(source).splitlines():
        line = raw.split(" #", 1)[0].strip()
        if line and not line.startswith("#"):
            lines.append(line)
    return lines


def _direct_pins(source: str) -> dict[str, tuple[str, str]]:
    """Normalised name to (operator, version): a source's pins and those it includes."""
    pins: dict[str, tuple[str, str]] = {}
    for line in _source_lines(source):
        if line == INCLUDES.get(source):
            pins |= _direct_pins(line.removeprefix("-r "))
        found = _PIN.match(line)
        if found:
            pins[_normalised(found["name"])] = (found["op"], found["version"])
    return pins


def _lock_entries(lock: str) -> dict[str, tuple[str, str | None, tuple[str, ...]]]:
    """Normalised name to (version, marker, hashes); every line of the lock accounted
    for: uv's header and notes, the one option, a package or one of its hashes."""
    entries: dict[str, tuple[str, str | None, tuple[str, ...]]] = {}
    current: str | None = None
    for number, line in enumerate(_text(lock).splitlines(), start=1):
        entry = _LOCK_ENTRY.match(line)
        if entry:
            assert entry["name"] not in entries, f"{lock}:{number}"
            current = entry["name"]
            entries[current] = (entry["version"], entry["marker"], ())
        elif _LOCK_HASH.match(line):
            assert current is not None, f"{lock}:{number}"
            version, marker, hashes = entries[current]
            entries[current] = (version, marker, (*hashes, line.split("sha256:")[1][:64]))
            if not line.endswith("\\"):
                current = None
        else:
            assert current is None, f"{lock}:{number}: a package whose hashes do not end"
            assert line in ("", ONLY_WHEELS) or line.lstrip().startswith("#"), f"{lock}:{number}"
    return entries


def _workflows() -> list[Path]:
    return sorted((ROOT / ".github" / "workflows").glob("*.y*ml"))


def _run_scripts(node: object) -> list[str]:
    """Every `run:` value of a parsed workflow."""
    if isinstance(node, dict):
        found = [str(value) for key, value in node.items() if key == "run"]
        for value in node.values():
            found += _run_scripts(value)
        return found
    if isinstance(node, list):
        return [script for item in node for script in _run_scripts(item)]
    return []


def _python_steps() -> list[dict[str, object]]:
    workflow = yaml.safe_load(_text(".github/workflows/ci.yml"))
    steps: list[dict[str, object]] = workflow["jobs"]["python"]["steps"]
    return steps


def _lock_check_script() -> str:
    (step,) = [step for step in _python_steps() if step.get("name") == LOCK_CHECK]
    assert set(step) == {"name", "run"}
    return str(step["run"])


# ── sources and locks ─────────────────────────────────────────────────────────────────────


def test_each_source_holds_pins_the_wheels_only_option_and_its_include() -> None:
    for source in LOCKS:
        lines = _source_lines(source)
        assert lines[0] == ONLY_WHEELS, source
        assert (INCLUDES.get(source) in lines) == (source in INCLUDES), source
        loose = [
            line
            for line in lines
            if not _PIN.match(line) and line not in (ONLY_WHEELS, INCLUDES.get(source))
        ]
        assert loose == [], source


def test_each_lock_names_its_command_and_hashes_every_package() -> None:
    for source, lock in LOCKS.items():
        lines = _text(lock).splitlines()
        # The command that made it: Dependabot's uv updater reads its options here.
        assert lines[:2] == [LOCK_HEADER, f"#    {COMPILE} {source} -o {lock}"], lock
        assert lines[2] == ONLY_WHEELS, lock
        entries = _lock_entries(lock)
        assert entries != {}, lock
        assert [name for name, (_, _, hashes) in entries.items() if not hashes] == [], lock


def test_each_lock_holds_the_pins_of_its_source() -> None:
    """The versions chosen by hand are the versions installed; a `>=` floor is met."""
    for source, lock in LOCKS.items():
        entries = _lock_entries(lock)
        for name, (operator, version) in _direct_pins(source).items():
            assert name in entries, (lock, name)
            locked = entries[name][0]
            if operator == "==":
                assert locked == version, (lock, name)
            else:
                wanted = tuple(int(part) for part in version.split("."))
                assert tuple(int(part) for part in locked.split(".")) >= wanted, (lock, name)


def test_the_locks_agree_on_every_package_they_share() -> None:
    """The tests run on the runtime packages of the image, at the same versions."""
    runtime = _lock_entries("requirements.txt")
    development = _lock_entries("requirements-dev.txt")
    assert set(runtime) <= set(development)
    assert {name: development[name] for name in runtime} == runtime
    # pip and setuptools of the image are not packages of the application.
    assert set(_lock_entries("requirements-build.txt")) == {"pip", "setuptools"}


def test_the_lock_python_is_the_image_python() -> None:
    """The locks are resolved for the Python the image and CI run (#325)."""
    dockerfile = _text("docker/web/Dockerfile")
    (image,) = re.findall(r"^FROM python:(\d+\.\d+)[-.\w]*\s*$", dockerfile, re.MULTILINE)
    assert f"--python-version {image} " in COMPILE


# ── every install reads a lock ────────────────────────────────────────────────────────────


# Any command that installs Python packages: pip (also as `python -m pip`), pipx, uv's
# own installers and uvx. Only `pip install` from a lock is allowed (below); `uv pip
# compile`, which installs nothing, is not matched.
_INSTALLER = re.compile(r"\bpip3? install\b|\bpipx\b|\buv(?:\.exe)? (?:pip|tool) install\b|\buvx\b")
# The variables and options that send pip or uv to another package index.
_INDEX_SETTING = re.compile(
    r"(?<![\w-])(PIP_INDEX_URL|PIP_EXTRA_INDEX_URL|UV_INDEX_URL|UV_EXTRA_INDEX_URL|UV_DEFAULT_INDEX"
    r"|UV_INDEX|--index-url|--extra-index-url|--default-index|--index)\b(?:[\s:=\"']+(\S*))?"
)
PYPI = "https://pypi.org/simple"
# Folders that are not the repository's own files.
_NOT_OURS = {".git", ".venv", "venv", "node_modules", "__pycache__"}


def _joined(text: str) -> list[str]:
    """The lines of a script or Dockerfile, a line ending in `\\` joined to the next one,
    comment lines left out."""
    lines = re.sub(r"\s*\\\n\s*", " ", text).splitlines()
    return [line.strip() for line in lines if not line.strip().startswith("#")]


def _dockerfiles() -> list[Path]:
    return sorted(
        path
        for path in ROOT.glob("**/Dockerfile*")
        if path.is_file() and not _NOT_OURS & set(path.relative_to(ROOT).parts)
    )


def _command_lines() -> list[tuple[str, str]]:
    """Every command line of the workflows' `run:` scripts and of every Dockerfile."""
    found: list[tuple[str, str]] = []
    for path in _workflows():
        for script in _run_scripts(yaml.safe_load(path.read_text(encoding="utf-8"))):
            found += [(path.name, line) for line in _joined(script)]
    for dockerfile in _dockerfiles():
        where = dockerfile.relative_to(ROOT).as_posix()
        found += [(where, line) for line in _joined(dockerfile.read_text(encoding="utf-8"))]
    return found


def _pip_installs() -> list[tuple[str, str]]:
    """Every line that installs Python packages, in the workflows and the Dockerfiles."""
    return [(where, line) for where, line in _command_lines() if _INSTALLER.search(line)]


# The one allowed form: `pip install` with the flags, one lock, at the end of the line.
_LOCKED_INSTALL = re.compile(rf"^(?:RUN )?(?:\S+ )*?pip install {re.escape(INSTALL)} (\S+)$")


def _is_locked_install(line: str) -> bool:
    found = _LOCKED_INSTALL.search(line)
    return bool(
        found
        # The Dockerfile reads the build lock where its bind mount puts it.
        and found[1].split("/")[-1] in LOCKS.values()
        # One install a line, and pip the only installer on it.
        and _INSTALLER.findall(line) == ["pip install"]
    )


def test_every_pip_install_reads_a_lock_with_its_hashes_and_wheels_only() -> None:
    installs = _pip_installs()
    assert [(where, line) for where, line in installs if not _is_locked_install(line)] == []
    assert sorted(installs) == sorted(
        [
            ("ci.yml", f"python -m pip install {INSTALL} requirements-build.txt"),
            ("ci.yml", f"pip install {INSTALL} requirements-dev.txt"),
            ("ci.yml", f"pip install {INSTALL} requirements-dev.txt"),
            (
                "docker/web/Dockerfile",
                "RUN --mount=type=bind,source=requirements-build.txt,"
                "target=/tmp/requirements-build.txt "
                f"pip install {INSTALL} /tmp/requirements-build.txt",
            ),
            ("docker/web/Dockerfile", f"RUN pip install {INSTALL} requirements.txt"),
        ]
    )


@pytest.mark.parametrize(
    ("script", "caught"),
    [
        pytest.param(f"pip install {INSTALL} requirements.txt", False, id="the-rule"),
        pytest.param(f"python -m pip \\\n  install {INSTALL} zz.txt", True, id="not-a-lock"),
        pytest.param("python -m pip \\\n  install zz-one", True, id="split-line"),
        pytest.param("RUN pipx install zz-one", True, id="pipx"),
        pytest.param("uv tool install zz-one", True, id="uv-tool"),
        pytest.param("uvx zz-one", True, id="uvx"),
        pytest.param("uv pip install zz-one", True, id="uv-pip"),
        pytest.param(
            f"uv pip install {INSTALL} requirements.txt", True, id="uv-pip-with-the-flags"
        ),
        pytest.param(
            f"pip install {INSTALL} requirements.txt && pip install zz-one",
            True,
            id="two-on-a-line",
        ),
        pytest.param(
            "python -m uv pip compile zz.in -o zz.txt", False, id="compile-installs-nothing"
        ),
    ],
)
def test_the_install_rule_reads_what_it_should(script: str, caught: bool) -> None:
    """The reader of the test above, on invented lines."""
    lines = [line for line in _joined(script) if _INSTALLER.search(line)]
    assert any(not _is_locked_install(line) for line in lines) == caught


def _other_indexes(text: str) -> list[tuple[str, str]]:
    """Each setting of an index in `text` whose value is not PyPI's (or is not given)."""
    settings = [(found[1], found[2] or "") for found in _INDEX_SETTING.finditer(text)]
    return [(name, value) for name, value in settings if value.strip("\"'").rstrip("/") != PYPI]


def test_no_workflow_or_dockerfile_points_pip_or_uv_at_another_index() -> None:
    """PyPI only: the locks were compiled against it, and an extra index lets a package of
    the same name and a higher version from elsewhere into a later compile."""
    found: list[tuple[str, str, str]] = []
    for path in [*_workflows(), *_dockerfiles()]:
        text = "\n".join(_joined(path.read_text(encoding="utf-8")))
        found += [(path.name, name, value) for name, value in _other_indexes(text)]
    assert found == []


